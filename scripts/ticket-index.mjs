import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../tickets/", import.meta.url));

function frontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  return Object.fromEntries(
    m[1].split(/\r?\n/).map((line) => {
      const i = line.indexOf(":");
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    }),
  );
}

const tickets = (sub) =>
  readdirSync(join(dir, sub), { withFileTypes: true })
    .filter((e) => e.isFile() && /^AV-\d+-.*\.md$/.test(e.name))
    .map((e) => (sub ? `${sub}/${e.name}` : e.name));

// Done tickets live in tickets/archive/ but stay in the index.
const rows = [...tickets(""), ...tickets("archive")]
  .sort((a, b) => a.split("/").pop().localeCompare(b.split("/").pop()))
  .map((f) => {
    const fm = frontmatter(readFileSync(join(dir, f), "utf8"));
    const depends = (fm.depends ?? "").replace(/[[\]]/g, "") || "-";
    return `| [${fm.id}](${f}) | ${fm.title} | ${fm.status} | ${depends} |`;
  });

const out = [
  "# Tickets",
  "",
  "Generated by `npm run tickets`. Do not edit by hand.",
  "",
  "| ID | Title | Status | Depends |",
  "|---|---|---|---|",
  ...rows,
  "",
].join("\n");

writeFileSync(join(dir, "INDEX.md"), out);
console.log(`tickets/INDEX.md: ${rows.length} tickets`);
